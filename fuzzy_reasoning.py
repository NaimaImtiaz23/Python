"""### 2. ABS Brake System (`abs_brake_system()` function)

This system simulates a simplified Anti-lock Braking System (ABS) that adjusts brake pressure based on vehicle speed and wheel slip. This is a common application for fuzzy logic in control engineering.
"""

# Define input and output variables
speed = ctrl.Antecedent(np.arange(0, 101, 1), 'speed') # Vehicle speed from 0-100 (e.g., km/h or mph)
slip = ctrl.Antecedent(np.arange(0, 11, 1), 'slip')   # Wheel slip from 0-10 (higher means more slip)
brake = ctrl.Consequent(np.arange(0, 101, 1), 'brake') # Brake pressure from 0-100% (e.g., control signal)

# Define membership functions for inputs (automatically generated)
speed.automf(3)
slip.automf(3)

# Define membership functions for output (manually defined triangular functions)
brake['low'] = fuzz.trimf(brake.universe, [0, 0, 50])        # Low brake pressure
brake['medium'] = fuzz.trimf(brake.universe, [0, 50, 100])  # Medium brake pressure
brake['high'] = fuzz.trimf(brake.universe, [50, 100, 100]) # High brake pressure

# Define fuzzy rules
# These rules dictate how brake pressure changes based on speed and slip
rule1 = ctrl.Rule(speed['poor'] | slip['poor'], brake['high']) # If speed is low OR slip is low (e.g., starting to spin), THEN brake high
rule2 = ctrl.Rule(speed['average'], brake['medium'])           # If speed is average, THEN brake medium
rule3 = ctrl.Rule(speed['good'] | slip['good'], brake['low'])    # If speed is high OR slip is high (e.g., good grip), THEN brake low

# Create the fuzzy control system
braking_ctrl = ctrl.ControlSystem([rule1, rule2, rule3])

# Create a simulation to compute the output
braking = ctrl.ControlSystemSimulation(braking_ctrl)

# Input values for speed and slip
braking.input['speed'] = 70
braking.input['slip'] = 3

# Compute the fuzzy inference
braking.compute()

# Print the defuzzified output (the crisp brake pressure value)
print(f"Brake: {braking.output['brake']:.2f}")

