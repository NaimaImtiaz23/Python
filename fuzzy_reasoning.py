"""This code demonstrates the application of fuzzy logic using the `scikit-fuzzy` library in Python. Fuzzy logic is a method of reasoning that resembles human reasoning, allowing for approximate rather than fixed and exact values. It's particularly useful in control systems where precise mathematical models are difficult to define.

The script defines two independent fuzzy logic control systems:

1.  **Restaurant Tipping System**: Calculates a tip percentage based on service and food quality.
2.  **ABS Brake System**: Determines brake pressure based on vehicle speed and wheel slip.

### Core Components of a Fuzzy Logic System (`skfuzzy`)

*   **Antecedent (Input Variable)**: These are the input conditions to the fuzzy system (e.g., `service`, `food`, `speed`, `slip`). They are defined over a specific range (`np.arange`).
*   **Consequent (Output Variable)**: This is the output of the fuzzy system (e.g., `tip`, `brake`). It's also defined over a range.
*   **Membership Functions (MFs)**: These functions define how well a specific value belongs to a fuzzy set (e.g., 'poor', 'average', 'good' service). `skfuzzy` provides methods like `automf` (automatically generates MFs) and `trimf` (triangular membership function) to define these.
*   **Fuzzy Rules**: These are IF-THEN statements that link the input fuzzy sets to the output fuzzy sets (e.g., "IF service is good THEN tip is high"). Logical operators like `|` (OR) and `&` (AND) are used.
*   **Control System**: This combines the antecedents, consequents, and rules into a complete fuzzy logic system.
*   **Control System Simulation**: This object allows you to input specific crisp values into the system, compute the fuzzy inference, and obtain a crisp output (defuzzification).

### 1. Restaurant Tipping System (`restaurant_tipping()` function)

This system simulates how a person might decide on a tip based on their perception of service and food quality. Let's break it down:
"""

import numpy as np
import skfuzzy as fuzz
from skfuzzy import control as ctrl
import matplotlib.pyplot as plt

# Define input and output variables
service = ctrl.Antecedent(np.arange(0, 11, 1), 'service') # Service quality from 0-10
food = ctrl.Antecedent(np.arange(0, 11, 1), 'food')     # Food quality from 0-10
tip = ctrl.Consequent(np.arange(0, 26, 1), 'tip')       # Tip percentage from 0-25%

# Define membership functions
# `automf(3)` automatically creates 'poor', 'average', 'good' membership functions
service.automf(3)
food.automf(3)

# For tip, specific triangular membership functions are defined manually
tip['low'] = fuzz.trimf(tip.universe, [0, 0, 13])      # Low tip: 0-13%
tip['medium'] = fuzz.trimf(tip.universe, [0, 13, 25])  # Medium tip: 0-25% (peaking at 13%)
tip['high'] = fuzz.trimf(tip.universe, [13, 25, 25])   # High tip: 13-25%

# Define fuzzy rules
# These are IF-THEN statements that capture human-like reasoning
rule1 = ctrl.Rule(service['poor'] | food['poor'], tip['low']) # IF service is poor OR food is poor, THEN tip is low
rule2 = ctrl.Rule(service['average'], tip['medium'])          # IF service is average, THEN tip is medium
rule3 = ctrl.Rule(service['good'] | food['good'], tip['high'])  # IF service is good OR food is good, THEN tip is high

# Create the fuzzy control system
tipping_ctrl = ctrl.ControlSystem([rule1, rule2, rule3])

# Create a simulation to compute the output based on inputs
tipping = ctrl.ControlSystemSimulation(tipping_ctrl)

# Input values for service and food quality
tipping.input['service'] = 6.5
tipping.input['food'] = 9.8

# Compute the fuzzy inference
tipping.compute()

# Print the defuzzified output (the crisp tip value)
print(f"Tip: {tipping.output['tip']:.2f}")

